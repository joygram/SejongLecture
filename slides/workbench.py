SLIDES = Path(__file__).resolve().parent
ROOT = SLIDES.parent
SOURCE = SLIDES / 'sejong-ai-writing.qmd'
OUTPUT = SLIDES / 'sejong-ai-writing.html'
ARTIFACTS = SLIDES / '.workbench'


def manifest():
    text = SOURCE.read_text(encoding='utf-8-sig')
    title = re.search(r'^title: "(.*)"', text, re.M).group(1)
    items = [{'title': title, 'notes': '표지. 강사 소개 후 오늘의 목표로 전환.', 'kind': '표지'}]
    # Ignore headings in fenced code and YAML.
    body = text.split('---', 2)[2]
    masked = re.sub(r'```[^\n]*\n.*?\n```', '', body, flags=re.S)
    headings = list(re.finditer(r'^(#{1,2}) (.+)$', masked, re.M))
    for i, heading in enumerate(headings):
        segment = masked[heading.end():headings[i+1].start() if i+1<len(headings) else len(masked)]
        notes = re.findall(r'::: notes\n(.*?)\n:::', segment, re.S)
        visible = re.sub(r'::: notes\n.*?\n:::', '', segment, flags=re.S)
        kind = '구분' if len(heading.group(1)) == 1 else '본문'
        for token, label in [('tile-grid', '카드'), ('decision-grid', '판단 카드'), ('before-after', '비교'), ('flow-line', '흐름'), ('qr-panel', '실습·QR'), ('story-layout', '이야기·일러스트'), ('bridge-art', '일러스트·흐름')]:
            if token in visible: kind = label
        if re.search(r'^\|', visible, re.M): kind += '·표'
        items.append({'title': re.sub(r'\s*\{.*?\}\s*$', '', heading.group(2)), 'notes': '\n'.join(notes), 'kind': kind})
    for i, item in enumerate(items):
        item['purpose'] = (re.search(r'^보여주는 이유: (.+)$',item['notes'],re.M).group(1) if re.search(r'^보여주는 이유: (.+)$',item['notes'],re.M) else '')
        item['insight'] = (re.search(r'^생각할 질문: (.+)$',item['notes'],re.M).group(1) if re.search(r'^생각할 질문: (.+)$',item['notes'],re.M) else '')
        item['notes'] = re.sub(r'^(보여주는 이유|생각할 질문): .+\n?', '', item['notes'],flags=re.M)
        item['index'] = i
        item['key'] = hashlib.sha256(item['title'].encode()).hexdigest()[:12]
    guide = json.loads((ROOT/'demo/presenter-guide.json').read_text(encoding='utf-8'))
    revision_source = json.dumps(guide,ensure_ascii=False) + text + (SLIDES/'sejong-slides.scss').read_text(encoding='utf-8-sig') + (SLIDES/'audience-only.lua').read_text(encoding='utf-8-sig') + (SLIDES/'SLIDE_PROMPT.txt').read_text(encoding='utf-8-sig') + (SLIDES/'slide-navigation.html').read_text(encoding='utf-8-sig')
    for source_path in [ROOT/'demo/cases/d-grade7/data.csv', ROOT/'demo/report-story.qmd', ROOT/'handout/card-template.html']:
        revision_source += hashlib.sha256(source_path.read_bytes()).hexdigest()
    for asset in sorted((SLIDES/'assets').glob('*.png')):
        revision_source += hashlib.sha256(asset.read_bytes()).hexdigest()
    return {'guide': guide, 'slides': items, 'revision': hashlib.sha256(revision_source.encode()).hexdigest()[:12],
            'prompt': (SLIDES/'SLIDE_PROMPT.txt').read_text(encoding='utf-8-sig')}


def build():
    quarto = shutil.which('quarto')
    if not quarto:
        candidates = [Path(os.environ.get('ProgramFiles', 'C:/Program Files'))/'Quarto/bin/quarto.exe', Path.home()/'AppData/Local/Programs/Quarto/bin/quarto.exe']
        quarto = next((str(p) for p in candidates if p.exists()), None)
    if not quarto:
        raise RuntimeError('Quarto 실행 파일 필요. 설치 후 PATH 또는 기본 설치 경로 확인.')
    subprocess.run([quarto, 'render', str(SOURCE)], cwd=ROOT, check=True)
    data = manifest()
    (SLIDES/'workbench/data.js').write_text('// Generated by workbench.py build; do not edit.\nwindow.WORKBENCH_DATA = '+json.dumps(data, ensure_ascii=False)+';\n', encoding='utf-8')
    write_presenter_guide(data['guide'])
    print(f"청중용 HTML + 워크벤치 {len(data['slides'])}장 갱신 완료")


def write_presenter_guide(guide):
    lines=['# 강사 시연 입력·질문 대응 가이드','', '- 생성 정본 = demo/presenter-guide.json, 갱신 = python slides/workbench.py build.','- 리허설 = 프로젝트 루트, AI 도구 로그인·원자료·완성본 사전 준비.','- 실시간 AI 응답 예문 동일성 보장 없음, 확인점으로 판정.','', '## 초입 질문','']
    lines += ['- '+x for x in guide['opening']]
    for step in guide['steps']:
        lines += ['', '## '+step['title'], '', '- 시간 = '+step['time'], '- 입력 위치 = '+step['where'], '- 말할 것 = '+step['say'], '', '```text', step['input'], '```', '', '- 확인점 = '+step['expect'], '- 실패 대응 = '+step['fallback']]
    lines += ['', '## Q&A 운영 전략', '']+['- '+x for x in guide['strategy']]
    for faq in guide['faqs']:
        lines += ['', '## '+faq['question'],'','- 짧은 답 = '+faq['answer'],'- 경계 = '+faq['boundary'],'- 연결 = '+faq['connect']]
    (ROOT/'demo/PRESENTER_GUIDE.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    tools=['# 내 보고서 환경 · 도구별 활용 가이드','', '- 확인 기준 = 2026-11-04 공식 문서, 개인·학교 계정의 실제 화면은 미검증.','- Google Workspace = Docs 등 Google 환경, ChatGPT Projects = 과제별 맥락을 모으는 기능.','- 공통 흐름 = 스타일 지침 → 원자료 → 요청 → 결과 검토 → 원본 보관.','- 계정 메뉴가 다르면 일반 채팅에 공통 지침·표·요청을 함께 붙여넣어 같은 과제 수행.']
    tools += ['', '## 공통 스타일 지침', '', '```text', guide['platforms'][0]['instructions'], '```']
    for item in guide['platforms']:
        tools += ['', '## '+item['name'], '', '- 용도 = '+item['purpose']]+['- '+step for step in item['steps']]
        tools += ['', '### 시험 입력','', '```text', item['trial'], '```', '', '- 대체 = '+item['fallback'], '- 확인 사항 = '+item['note']]
        tools += ['- 공식 안내 = '+', '.join('['+src['title']+']('+src['url']+')' for src in item['sources'])]
    tools += ['', '## 다음 작업에 남길 것', '', '- 원자료·출처·기준일, 내가 고른 계산 기준.','- 편집 가능한 문서 원본, 공통 스타일 지침, 수정 기록.','- 실제로 확인한 문장·수치·인용과 AI 사용 고지.']
    (ROOT/'handout/tool-workflows.md').write_text('\n'.join(tools)+'\n',encoding='utf-8')
    student_cards=[]
    for number,(title,index) in enumerate([('카드 1 · 우리 메모로 초안 쓰기',1),('카드 2 · 표에서 세 문장으로',3),('카드 3 · 우리 뜻에 맞게 퇴고',5),('완성 뒤 · 팀 채팅방에 공유',8)]):
        step=guide['steps'][index]
        key='card-'+str(number)
        student_cards.append('<article><div class="heading"><h2>'+html.escape(title)+'</h2><button type="button" data-copy="'+key+'">복사</button></div><p class="think">'+html.escape(step['insight'])+'</p><textarea id="'+key+'" readonly aria-label="'+html.escape(title)+' 입력문">'+html.escape(step['input'])+'</textarea><p class="hint" id="'+key+'-status" aria-live="polite">읽어보고 내 글에 맞게 바꿔 입력하세요.</p></article>')
    template=(ROOT/'handout/card-template.html').read_text(encoding='utf-8-sig')
    (ROOT/'handout/prompts.html').write_text('<!-- Generated by slides/workbench.py build from card-template.html and presenter-guide.json. -->\n'+template.replace('{{CARDS}}','\n'.join(student_cards)),encoding='utf-8')




def check():
    from playwright.sync_api import sync_playwright
    ARTIFACTS.mkdir(exist_ok=True)
    data = manifest()
    built = json.loads((SLIDES/'workbench/data.js').read_text(encoding='utf-8').split('window.WORKBENCH_DATA = ',1)[1].rstrip(';\n'))
    if built['revision'] != data['revision']:
        raise RuntimeError('원본 변경 감지: 먼저 python slides/workbench.py build 실행 필요')
    result = {'revision': data['revision'], 'viewports': [], 'manual': '내용·디자인·QR 실제 스캔은 사람 검수 필요'}
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto(OUTPUT.as_uri())
        page.wait_for_function('window.Reveal && Reveal.isReady()')
        page.wait_for_function('Reveal.getConfig().scrollActivationWidth === 0 && !Reveal.isScrollView()')
        page.evaluate('document.fonts.ready')
        page.evaluate("Reveal.configure({transition:'none', backgroundTransition:'none'})")
        if page.locator('aside.notes').count():
            raise RuntimeError('공개 HTML에 발표자 노트 잔존')
        count = page.evaluate('Reveal.getSlides().length')
        if count != len(data['slides']):
            raise RuntimeError(f'원본·출력 장수 불일치: {len(data["slides"])} / {count}')
        for width, height in [(1920,1080),(1366,768),(1024,768),(390,844)]:
            page.set_viewport_size({'width':width,'height':height})
            page.wait_for_timeout(200)
            issues = []
            for i in range(count):
                page.evaluate('(i)=>{let x=Reveal.getIndices(Reveal.getSlides()[i]);Reveal.slide(x.h,x.v)}', i)
                page.wait_for_timeout(30)
                found = page.evaluate('''()=>{
                    const s=Reveal.getCurrentSlide(),r=s.getBoundingClientRect(),z=Reveal.getScale();
                    const errors=[];
                    for(const e of s.querySelectorAll('h1,h2,h3,p,table,pre,ul,ol,img,.tile,.qr-panel')) {
                        const b=e.getBoundingClientRect(); if(!b.height)continue;
                        if(b.bottom>r.bottom-48*z+2||b.right>r.right-30*z+2||b.left< -1||b.right>innerWidth+1) errors.push('본문 잘림: '+e.tagName);
                        if(e.tagName==='IMG'&&(!e.complete||!e.naturalWidth))errors.push('이미지 로드 실패');
                    }
                    const qr=s.querySelector('.qr-panel'); if(qr){const q=qr.getBoundingClientRect(); for(const e of s.querySelectorAll(':scope > table,:scope > p')){const b=e.getBoundingClientRect();if(b.left<q.right&&b.right>q.left&&b.top<q.bottom&&b.bottom>q.top)errors.push('QR·본문 겹침');}}
                    const text=s.innerText;
                    for(const term of ['DECISIONS.md','SOURCE.md','CHECK.md','pipeline.py','테더링','강사 화면에서'])if(text.includes(term))errors.push('내부 운영 문구: '+term);
                    return [...new Set(errors)];
                }''')
                if found: issues.append({'slide':i+1,'title':data['slides'][i]['title'],'issues':found})
                if width == 1366:
                    page.screenshot(path=str(ARTIFACTS/f'slide-{i+1:02}.png'))
            result['viewports'].append({'size':f'{width}×{height}','slides':count,'issues':issues})
        # Exercise real mouse clicks without adding presentation controls.
        page.set_viewport_size({'width':1280,'height':720})
        if page.evaluate('Reveal.getConfig().scrollActivationWidth') != 0:
            raise RuntimeError('좁은 화면에서 스크롤 전환 방지 설정 누락')
        page.evaluate('Reveal.slide(0, 0)')
        page.locator('#title-slide h1').click()
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("opening-poll")')
        page.locator('section.present h2').click()
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("story-opening")')
        page.locator('.present .chat-bubble.friend').click()
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("lecture-goals")')
        page.locator('section.present h2').click(modifiers=['Shift'])
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("story-opening")')
        page.locator('section.present .story-art img').click()
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("lecture-goals")')
        page.locator('section.present h2').click()
        page.wait_for_function('Reveal.getCurrentSlide().classList.contains("title-slide")')
        page.locator('section.title-slide.present h1').click()
        page.wait_for_function('Reveal.getSlides().indexOf(Reveal.getCurrentSlide()) === 5')
        index_before_link = page.evaluate('Reveal.getSlides().indexOf(Reveal.getCurrentSlide())')
        page.evaluate("""()=>{const a=document.createElement('a');a.id='navigation-link-test';a.href='https://example.com/';a.textContent='링크 검사';a.onclick=e=>e.preventDefault();Reveal.getCurrentSlide().append(a)}""")
        page.locator('#navigation-link-test').click()
        if page.evaluate('Reveal.getSlides().indexOf(Reveal.getCurrentSlide())') != index_before_link:
            raise RuntimeError('링크 클릭 시 슬라이드가 이동함')
        page.locator('#navigation-link-test').evaluate('(e)=>e.remove()')
        page.evaluate('Reveal.slide(0, 0)')
        page.locator('#title-slide h1').click(modifiers=['Shift'])
        if page.evaluate('Reveal.getSlides().indexOf(Reveal.getCurrentSlide())') != 0:
            raise RuntimeError('첫 장에서 이전 이동 경계 실패')
        page.evaluate("""()=>{const x=Reveal.getIndices(Reveal.getSlides().at(-1));Reveal.slide(x.h,x.v)}""")
        page.locator('section.slide.present h2').click()
        if page.evaluate('Reveal.getSlides().indexOf(Reveal.getCurrentSlide())') != count-1:
            raise RuntimeError('마지막 장에서 다음 이동 경계 실패')
        result['navigation'] = '본문·이미지 클릭 / Shift+클릭 / 구분 장 이동 / 링크 제외 / 첫·끝 경계 통과'
        browser.close()
    (ARTIFACTS/'check.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    # The workbench reads this script even when opened directly from disk.
    (SLIDES/'workbench/check-data.js').write_text('// Generated by workbench.py check; do not edit.\nwindow.WORKBENCH_CHECK = '+json.dumps(result,ensure_ascii=False)+';\n',encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False,indent=2))
    return int(any(v['issues'] for v in result['viewports']))


STUDENT_URL = 'https://joygram.github.io/SejongLecture/handout/prompts.html'


def qr():
    import qrcode
    import qrcode.image.svg
    code = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=10, border=4)
    code.add_data(STUDENT_URL)
    code.make(fit=True)
    code.make_image(image_factory=qrcode.image.svg.SvgPathFillImage).save(SLIDES/'prompts-qr.svg')
    print('prompts-qr.svg', STUDENT_URL)


def pdf():
    from playwright.sync_api import sync_playwright
    target = SLIDES/'sejong-ai-writing.pdf'
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto(OUTPUT.as_uri()+'?print-pdf')
        page.wait_for_function('window.Reveal && Reveal.isReady()')
        page.evaluate('document.fonts.ready')
        page.wait_for_load_state('networkidle')
        page.pdf(path=str(target), prefer_css_page_size=True, print_background=True)
        browser.close()
    print(target.name)


def serve(port):
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT))
    print(f'워크벤치: http://127.0.0.1:{port}/slides/workbench/', flush=True)
    print('청중 화면 공유: slides/sejong-ai-writing.html / 노트: 워크벤치에서만 표시',flush=True)
    with http.server.ThreadingHTTPServer(('127.0.0.1',port),handler) as server:
        server.serve_forever()


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command',choices=['build','check','qr','pdf','serve'])
    parser.add_argument('--port',type=int,default=8765)
    args=parser.parse_args()
    try:
        if args.command=='build': build()
        elif args.command=='check': sys.exit(check())
        elif args.command=='qr': qr()
        elif args.command=='pdf': pdf()
        else: serve(args.port)
    except (RuntimeError,subprocess.CalledProcessError,ImportError,OSError) as exc:
        print(str(exc),file=sys.stderr);sys.exit(1)
